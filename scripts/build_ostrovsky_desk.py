def load_segments() -> list[dict]:
    raw = json.loads((SRC / "дебаты.json").read_text(encoding="utf-8"))
    segs = []
    for i, s in enumerate(raw["segments"]):
        text = (s.get("text") or "").strip()
        if not text:
            continue
        segs.append(
            {
                "id": i,
                "start": round(float(s["start"]), 2),
                "end": round(float(s.get("end") or s["start"]), 2),
                "start_fmt": clock(s["start"]),
                "text": text,
            }
        )
    duration = float(raw.get("duration") or segs[-1]["end"])
    return segs, duration


def enrich_errors() -> list[dict]:
    out = []
    for e in ERRORS:
        row = dict(e)
        row["start_fmt"] = clock(e["start"])
        row["clip_fmt"] = [clock(e["clip"][0]), clock(e["clip"][1])]
        out.append(row)
    return out


def enrich_chapters() -> list[dict]:
    return [{**c, "start_fmt": clock(c["start"])} for c in CHAPTERS]


