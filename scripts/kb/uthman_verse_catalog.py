def V(en: str, hook: str, ru: str | None = None) -> dict:
    q = quote(en, safe="")
    return {
        "ref": ru or en,
        "en": en,
        "hook": hook,
        "url": RUSV.format(q),
        "url_en": NRSV.format(q),
    }


def G(id: str, title: str, move: str, christian: str, verses: list[dict]) -> dict:
    return {
        "id": id,
        "title": title,
        "move": move,
        "christian": christian,
        "verses": verses,
        "count": len(verses),
    }


