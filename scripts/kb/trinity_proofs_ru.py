def _ref(ref: str) -> str:
    return quote(ref, safe="")


def bq(ru: str, en: str, cite: str, ref: str) -> dict:
    return Q(ru, cite, "Синодальный перевод", RUSV.format(_ref(ref)), orig=en)


def P(
    *,
    id: str,
    hook: str,
    they_say: str,
    they_claim: str,
    counter: str,
    steelman: str,
    verses: list[dict],
    they_quotes: list | None = None,
    counter_quotes: list | None = None,
    pattern: str | None = None,
) -> dict:
    d = {
        "id": id,
        "hook": hook,
        "they_say": they_say,
        "they_claim": they_claim,
        "counter": counter,
        "steelman": steelman,
        "verses": verses,
        "count": len(verses),
    }
    if they_quotes:
        d["they_quotes"] = they_quotes
    if counter_quotes:
        d["counter_quotes"] = counter_quotes
    if pattern:
        d["pattern"] = pattern
    return d


